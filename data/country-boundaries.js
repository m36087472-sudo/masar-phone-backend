function isInBoundingBox(lon, lat, countryCode) {
  const bb = BOUNDING_BOXES[countryCode];
  if (!bb) return false;
  const [lonMin, latMin, lonMax, latMax] = bb;
  return lon >= lonMin && lon <= lonMax && lat >= latMin && lat <= latMax;
}

function getCountryFeature(countryCode) {
  return FEATURES[countryCode] ?? null;
}

